"""Package this static site without dependencies or publishing to a host."""
import argparse
import html
import ipaddress
import os
from pathlib import Path
import shutil
from urllib.parse import quote, unquote, urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- PRODUCTION_METADATA: generated by scripts/build_static.py with a confirmed SITE_URL. -->'
SOCIAL_IMAGE = 'assets/images/hero/hero-04.png'
SOCIAL_ALT = 'Retrato de perfil com óculos escuros e jaqueta preta, diante de luzes e fundo urbano com movimento.'
PUBLIC_EXTENSIONS = {'.css', '.js', '.png', '.jpeg', '.jpg', '.webp', '.mp4'}


def production_url(value):
    """Require a public HTTPS URL; never derive a production host from local state."""
    parsed = urlsplit(value)
    host = parsed.hostname or ''
    if (parsed.scheme != 'https' or not host or parsed.username or parsed.password
            or parsed.query or parsed.fragment or parsed.port not in (None, 443)
            or any(c.isspace() for c in value) or '\\' in value):
        raise ValueError('SITE_URL deve ser uma URL HTTPS pública, sem credenciais, query ou fragmento.')
    if host == 'localhost' or host.endswith(('.localhost', '.local')) or '.' not in host:
        raise ValueError('SITE_URL não pode apontar para um endereço local.')
    try:
        address = ipaddress.ip_address(host)
    except ValueError:
        pass
    else:
        if not address.is_global:
            raise ValueError('SITE_URL não pode apontar para um endereço local.')
    path = unquote(parsed.path)
    if any(part in ('.', '..') for part in path.split('/')) or '\\' in path:
        raise ValueError('SITE_URL contém um caminho inválido.')
    path = quote(path.rstrip('/') + '/', safe='/~:@!$&\'()*+,;=-._')
    return urlunsplit(('https', parsed.netloc, path, '', ''))


def production_metadata(site_url):
    url = html.escape(site_url, quote=True)
    image = html.escape(site_url + SOCIAL_IMAGE, quote=True)
    alt = html.escape(SOCIAL_ALT, quote=True)
    return '\n    '.join([
        f'<link rel="canonical" href="{url}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:image" content="{image}">',
        '<meta property="og:image:type" content="image/png">',
        '<meta property="og:image:width" content="941">',
        '<meta property="og:image:height" content="1672">',
        f'<meta property="og:image:alt" content="{alt}">',
        f'<meta name="twitter:image" content="{image}">',
        f'<meta name="twitter:image:alt" content="{alt}">',
    ])


def build(output, site_url=None):
    site_url = production_url(site_url) if site_url else None
    output = Path(output).resolve()
    if output.exists():
        raise ValueError('A saída deve ser uma pasta nova; nenhum diretório existente será apagado.')
    page = (ROOT / 'index.html').read_text(encoding='utf-8')
    if page.count(MARKER) != 1:
        raise ValueError('Marcador de metadados ausente ou duplicado.')
    if site_url:
        page = page.replace(MARKER, production_metadata(site_url))
    # Copy only public assets. Repository files, tests, docs and local settings stay out.
    assets = []
    for asset in (ROOT / 'assets').rglob('*'):
        if not asset.is_file():
            continue
        relative = asset.relative_to(ROOT)
        if asset.is_symlink() or any(part.startswith('.') for part in relative.parts):
            raise ValueError('Asset oculto ou link simbólico não permitido na publicação.')
        # Original MOV masters stay in the repository; production serves their MP4 counterparts.
        if asset.suffix.lower() == '.mov':
            continue
        if asset.suffix.lower() not in PUBLIC_EXTENSIONS:
            raise ValueError('Tipo de arquivo não permitido nos assets públicos.')
        assets.append(asset)
    output.mkdir(parents=True)
    (output / 'index.html').write_text(page, encoding='utf-8')
    robots = (ROOT / 'robots.txt').read_text(encoding='utf-8')
    if site_url:
        robots += f'\nSitemap: {site_url}sitemap.xml\n'
        sitemap = ('<?xml version="1.0" encoding="UTF-8"?>\n'
                   '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
                   f'  <url><loc>{html.escape(site_url)}</loc></url>\n</urlset>\n')
        (output / 'sitemap.xml').write_text(sitemap, encoding='utf-8')
    (output / 'robots.txt').write_text(robots, encoding='utf-8')
    for asset in assets:
        destination = output / asset.relative_to(ROOT)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(asset, destination)
    return len(assets)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'dist')
    parser.add_argument('--site-url', default=os.environ.get('SITE_URL'))
    args = parser.parse_args()
    try:
        count = build(args.output, args.site_url)
    except ValueError as error:
        parser.error(str(error))
    print(f'Pacote estático criado: {args.output} ({count} assets).')
    if not args.site_url:
        print('PENDENTE: SITE_URL não definida; canonical, URLs sociais e sitemap não foram gerados.')
